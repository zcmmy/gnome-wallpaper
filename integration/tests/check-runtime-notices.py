#!/usr/bin/env python3
"""Runtime notices must survive packaging and missing declarations must fail."""
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

module_path = Path(__file__).resolve().parents[1] / 'scripts/runtime_notices.py'
spec = importlib.util.spec_from_file_location('runtime_notices', module_path)
notices = importlib.util.module_from_spec(spec)
spec.loader.exec_module(notices)


class RuntimeNoticesTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.sysroot = self.root / 'sysroot'
        self.output = self.root / 'build/output'
        self.dest = self.root / 'licenses'
        self.common = self.root / 'common'
        for name in ('LICENSE', 'NOTICE.md', 'renderer/source/LICENSE',
                     'third_party/sources.lock.json', 'third_party/README.md',
                     'third_party/COMPONENT-NOTICES.md',
                     'renderer/source/CMakeModules/README.md', 'vendor/LICENSE'):
            self.write(self.root / name, 'Synthetic notice: ' + name + '\n')
        self.write(self.root / 'third_party/licenses.json', json.dumps({
            'bundled_external_license_files': ['vendor/LICENSE'],
            'additional_license_files': []}))
        self.write(self.sysroot / 'share/doc/libglm-dev/copyright', 'Synthetic GLM notice\n')
        self.write(self.sysroot / 'share/doc/libglew2.2/copyright',
                   'Synthetic copyright references /usr/share/common-licenses/CC0-1.0\n')
        for name in (*notices.COMMON_LICENSES, 'CC0-1.0'):
            self.write(self.common / name, 'Synthetic license: ' + name)

    def write(self, path, text):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

    def collect(self, libraries=()):
        notices.collect_notices(self.root, self.sysroot, self.output,
                                self.dest, libraries, self.common)

    def test_complete_notices_and_referenced_license(self):
        self.collect(['libGLEW.so.2.2', 'liblinux-wallpaperengine-lib.so'])
        self.assertEqual((self.dest / 'source/vendor/LICENSE').read_bytes(),
                         (self.root / 'vendor/LICENSE').read_bytes())
        self.assertTrue((self.dest / 'common/CC0-1.0').is_file())
        self.assertTrue((self.dest / 'libglm-dev-copyright').is_file())

    def test_unknown_library_is_rejected_before_writing(self):
        with self.assertRaisesRegex(ValueError, 'libunreviewed'):
            self.collect(['libunreviewed.so.1'])
        self.assertFalse(self.dest.exists())

    def test_missing_package_or_referenced_license_is_rejected(self):
        (self.common / 'CC0-1.0').unlink()
        with self.assertRaises(FileNotFoundError):
            self.collect(['libGLEW.so.2.2'])
        self.assertFalse(self.dest.exists())
        (self.sysroot / 'share/doc/libglm-dev/copyright').unlink()
        with self.assertRaises(FileNotFoundError):
            self.collect()
        self.assertFalse(self.dest.exists())

    def test_generated_protocol_notice_is_preserved(self):
        self.write(self.output.parent / 'wayland/xdg-shell-protocol.c',
                   '/* Generated by wayland-scanner */\n/* Copyright Test Author\nTest license */\nint code;')
        self.write(self.sysroot / 'share/doc/wayland-protocols/copyright', 'Synthetic protocol package notice')
        self.collect()
        self.assertEqual((self.dest / 'protocols/xdg-shell-protocol.c.LICENSE').read_text(),
                         'Copyright Test Author\nTest license\n')

    def test_protocol_without_notice_is_rejected(self):
        self.write(self.output.parent / 'wayland/xdg-shell-protocol.c', '/* Generated */\nint code;')
        self.write(self.sysroot / 'share/doc/wayland-protocols/copyright', 'Synthetic notice')
        with self.assertRaisesRegex(ValueError, 'lacks a copyright'):
            self.collect()
        self.assertFalse(self.dest.exists())

    def test_missing_index_entry_is_rejected(self):
        (self.root / 'vendor/LICENSE').unlink()
        with self.assertRaises(FileNotFoundError):
            self.collect()
        self.assertFalse(self.dest.exists())


if __name__ == '__main__':
    unittest.main()
